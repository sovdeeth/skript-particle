"""Generates a Skript test script that parses every @Example/@Examples string of the addon's syntax classes."""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
out = Path(sys.argv[2])

STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')


def unescape(s: str) -> str:
    return s.encode("utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8")


def examples_of(text: str) -> list[str]:
    lines = []
    for m in re.finditer(r'@Examples?\(', text):
        i = m.end()
        depth = 1
        j = i
        in_str = False
        while depth:
            c = text[j]
            if not in_str and text.startswith('"""', j):
                j = text.index('"""', j + 3) + 3
                continue
            if in_str:
                if c == '\\':
                    j += 1
                elif c == '"':
                    in_str = False
            elif c == '"':
                in_str = True
            elif c == '(':
                depth += 1
            elif c == ')':
                depth -= 1
            j += 1
        inner = text[i:j - 1].strip()
        if inner.startswith('"""'):
            # text block: strip the incidental indentation, which the closing delimiter's line also counts towards
            body = inner[3:-3]
            raw = body.split("\n")[1:]
            margin = min(len(l) - len(l.lstrip()) for l in raw if l.strip() or l is raw[-1])
            lines.extend(unescape(l[margin:]) for l in raw if l.strip())
        else:
            for s in STRING.findall(inner):
                lines.extend(unescape(s).split("\n"))
    return lines


def indent_of(line: str) -> int:
    expanded = line.replace("    ", "\t")
    return len(expanded) - len(expanded.lstrip("\t"))


def normalise(line: str) -> str:
    return "\t" * indent_of(line) + line.strip()


def close_empty_sections(lines: list[str]) -> list[str]:
    result = []
    for k, line in enumerate(lines):
        result.append(line)
        if line.rstrip().endswith(":") and not line.lstrip().startswith("#"):
            nxt = lines[k + 1] if k + 1 < len(lines) else None
            if nxt is None or indent_of(nxt) <= indent_of(line):
                result.append("\t" * (indent_of(line) + 1) + "stop")
    return result


blocks = []  # (name, structure lines)
for path in sorted(src.rglob("*.java")):
    lines = [normalise(l) for l in examples_of(path.read_text(encoding="utf-8")) if l.strip()]
    if not lines:
        continue
    functions, body = [], []
    target = body
    for line in lines:
        if line.startswith("function "):
            target = functions
        elif indent_of(line) == 0:
            target = body
        target.append(line)
    name = path.stem
    if functions:
        blocks.append((name + "-functions", close_empty_sections(functions)))
    if body:
        trigger = ["command /spdoc-" + name.lower() + ":", "\ttrigger:"]
        trigger += ["\t\t" + l for l in close_empty_sections(body)]
        blocks.append((name, trigger))

with out.open("w", encoding="utf-8", newline="\n") as f:
    f.write("# GENERATED by src/test/gen_doc_examples.py - do not edit. Every documentation example must parse.\n")
    f.write("# Regenerate after changing any @Example (from the repository root):\n")
    f.write("#   python skript-particle/src/test/gen_doc_examples.py"
            " skript-particle/src/main/java/com/sovdee/skriptparticles/skript"
            " skript-particle/src/test/scripts/docexamples.sk\n\n")
    for name, structure in blocks:
        f.write("parse:\n")
        f.write("\tresults: {sp::doc::%s::*}\n" % name)
        f.write("\tcode:\n")
        for l in structure:
            f.write("\t\t" + l + "\n")
        f.write("\n")
    for name, _ in blocks:
        f.write('test "docs of %s parse":\n' % name)
        f.write('\tassert {sp::doc::%s::*} is not set with "%%{sp::doc::%s::*}%%"\n' % (name, name))
        f.write('\tdelete {sp::doc::%s::*}\n\n' % name)
print(len(blocks), "blocks")
