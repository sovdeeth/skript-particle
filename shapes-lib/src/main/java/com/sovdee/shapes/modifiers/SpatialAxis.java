package com.sovdee.shapes.modifiers;

/**
 * A spatial coordinate axis.
 * Used to specify the output displacement axis of a {@link WaveModifier}.
 */
public enum SpatialAxis {
    /**
     * The X axis.
     */
    X,

    /**
     * The Y axis.
     */
    Y,

    /**
     * The Z axis.
     */
    Z
}
